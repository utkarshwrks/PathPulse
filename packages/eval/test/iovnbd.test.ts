import { describe, expect, it } from 'vitest';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import type { SensorSample } from '@pathpulse/nav-core';

/**
 * The converted IO-VNBD logs — TIER R.
 *
 * ★ WHAT THESE ASSERTIONS ARE FOR ★
 * A replay log is data, not code, so nothing else in the suite would notice if
 * the converter silently changed. And the failures it can produce are not
 * crashes: a gyro axis permuted, a sign inverted, a speed column read in the
 * wrong unit. Each of those yields a log that parses perfectly, replays
 * perfectly, and describes a drive that never happened — which then becomes a
 * published number.
 *
 * Every check here corresponds to a trap that was actually hit while writing
 * scripts/iovnbd-to-replay.mjs. None of them is hypothetical.
 */

const HERE = new URL('.', import.meta.url).pathname;
const REPLAY = join(HERE, '../../../data/replay');

function load(name: string): SensorSample[] | null {
  const file = join(REPLAY, name);
  if (!existsSync(file)) return null;
  return readFileSync(file, 'utf8')
    .trim()
    .split('\n')
    .map((l) => JSON.parse(l) as SensorSample);
}

const LOGS = ['iovnbd_S1.jsonl', 'iovnbd_S3c.jsonl'];

/** Wrap a heading difference into (-180, 180]. */
function wrap(d: number): number {
  return ((d + 540) % 360) - 180;
}

describe('IO-VNBD replay logs (Tier R)', () => {
  const available = LOGS.filter((n) => existsSync(join(REPLAY, n)));

  it('the converted logs are present', () => {
    // They are generated by `node scripts/iovnbd-to-replay.mjs` from the
    // dataset ml/data/download.py fetches. Skipping silently would let the
    // rest of this file pass vacuously.
    expect(available.length).toBeGreaterThan(0);
  });

  for (const name of available) {
    describe(name, () => {
      const samples = load(name)!;

      it('★ has strictly increasing timestamps', () => {
        // The engine's step-1 guard drops any sample that does not advance the
        // clock, silently. A log with repeats scores as a much shorter drive
        // than it is — and S3b really does have them: 6,813 raw rows become
        // 2,043 samples.
        for (let i = 1; i < samples.length; i++) {
          expect(samples[i]!.t).toBeGreaterThan(samples[i - 1]!.t);
        }
      });

      it('is sampled at the dataset\'s native 10 Hz, not upsampled', () => {
        // The build guide invites resampling to 50 Hz. There is no information
        // above 5 Hz in the recording, so interpolated samples would be
        // invented data that the engine would faithfully integrate.
        const dts: number[] = [];
        for (let i = 1; i < samples.length; i++) dts.push(samples[i]!.t - samples[i - 1]!.t);
        dts.sort((a, b) => a - b);
        expect(dts[Math.floor(dts.length / 2)]).toBe(100);
      });

      it('★ carries specific force in m/s^2 with gravity included', () => {
        // Checks the unit AND that gravity was not removed: nav-core expects
        // specific force, and a log with gravity already subtracted would read
        // as permanent free-fall.
        const mags = samples
          .filter((s) => s.imu)
          .map((s) => Math.hypot(s.imu!.ax, s.imu!.ay, s.imu!.az))
          .sort((a, b) => a - b);
        const median = mags[Math.floor(mags.length / 2)]!;
        expect(median).toBeGreaterThan(9.4);
        expect(median).toBeLessThan(10.4);
      });

      it('reports angular rate in rad/s, not deg/s', () => {
        // A car's yaw rate peaks near 0.5 rad/s. In deg/s the same turn would
        // read about 30, so anything above a few rad/s is the wrong unit.
        const worst = samples
          .filter((s) => s.imu)
          .reduce((m, s) => Math.max(m, Math.abs(s.imu!.gx), Math.abs(s.imu!.gy), Math.abs(s.imu!.gz)), 0);
        expect(worst).toBeLessThan(6);
      });

      it('★ attaches each GNSS fix once, not to every sample', () => {
        // The CSV repeats the GPS columns on all ten rows of each second.
        // Emitting a fix on every row would tell the engine it has a 10 Hz
        // receiver, and every adaptive-timeout and Doppler-hold decision
        // downstream would be computed from a fiction. SensorLoopService.java
        // has the same rule for the same reason.
        const fixes = samples.filter((s) => s.gnss).length;
        expect(fixes).toBeGreaterThan(0);
        expect(fixes).toBeLessThan(samples.length / 10);
      });

      it('does not invent a barometer', () => {
        // IO-VNBD has none. A fabricated pressure would feed the altimeter and
        // the ESKF's vertical channel with a number that means nothing.
        expect(samples.some((s) => s.baro !== undefined)).toBe(false);
      });

      it('reports plausible vehicle speeds', () => {
        // ★ THE HEADER SAYS Kmh AND THE COLUMN IS m/s ★ Read as km/h the whole
        // drive is a crawl: S1's peak came out at 5.2 m/s for a car on a trunk
        // road. Anything under 8 m/s peak means the conversion regressed.
        const speeds = samples
          .map((s) => s.gnss?.speedMps)
          .filter((v): v is number => typeof v === 'number');
        if (speeds.length < 10) return;
        expect(Math.max(...speeds)).toBeGreaterThan(8);
        expect(Math.max(...speeds)).toBeLessThan(60);
      });
    });
  }

  it('★ a real 90-degree turn integrates to 90 degrees', () => {
    // ★ THE CHECK THAT CAUGHT AN INVERTED GYRO ★
    // The axis mapping was first derived against the car's CAN yaw rate and
    // came out backwards, because CAN follows ISO 8855 (positive
    // counter-clockwise) and GNSS heading is a compass bearing (positive
    // clockwise). Every magnitude agreed and every sign was opposite.
    //
    // This asserts the thing the estimator actually needs: that integrating the
    // recovered yaw rate between two fixes reproduces the heading change those
    // fixes report, in both magnitude AND sign.
    const samples = load('iovnbd_S1.jsonl');
    if (!samples) return;

    const fixes = samples.filter(
      (s) => s.gnss && Number.isFinite(s.gnss.headingDeg) && (s.gnss.speedMps ?? 0) > 4,
    );
    const predicted: number[] = [];
    const truth: number[] = [];
    for (let i = 1; i < fixes.length; i++) {
      const a = fixes[i - 1]!;
      const b = fixes[i]!;
      if (b.t - a.t > 15_000) continue;
      const dHead = wrap(b.gnss!.headingDeg! - a.gnss!.headingDeg!);
      if (Math.abs(dHead) < 60) continue; // only substantial turns

      let yawRad = 0;
      for (let k = 1; k < samples.length; k++) {
        const s = samples[k]!;
        if (s.t <= a.t) continue;
        if (s.t > b.t) break;
        const dt = (s.t - samples[k - 1]!.t) / 1000;
        if (dt <= 0 || dt > 0.5 || !s.imu) continue;
        // The phone is level in these sequences, so up is close to +Z and the
        // yaw rate is -gz. nav-core does this properly against measured
        // gravity; here the approximation is good enough to check a sign.
        yawRad += -s.imu.gz * dt;
      }
      predicted.push((yawRad * 180) / Math.PI);
      truth.push(dHead);
    }
    expect(predicted.length).toBeGreaterThan(10);

    // ★ ASSERTED STATISTICALLY, NOT PER SEGMENT ★
    // A single segment can legitimately disagree: GPS heading is only reported
    // at each fix, roughly 9 s apart here, and a stretch containing an S-bend
    // nets out to a small heading change while the gyro saw two large opposite
    // ones. What cannot happen, if the axes and signs are right, is systematic
    // disagreement across a hundred turns.
    const agree = predicted.filter((p, i) => Math.sign(p) === Math.sign(truth[i]!)).length;
    expect(agree / predicted.length).toBeGreaterThan(0.9);

    // Slope through the origin. An inverted gyro gives about -1; a permuted
    // axis gives something far from 1. Measured: +0.917 (S1), +1.002 (S3c).
    let num = 0;
    let den = 0;
    for (let i = 0; i < predicted.length; i++) {
      num += predicted[i]! * truth[i]!;
      den += truth[i]! * truth[i]!;
    }
    const slope = num / den;
    expect(slope).toBeGreaterThan(0.75);
    expect(slope).toBeLessThan(1.25);
  });
});
