import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { parseJsonl, runEval } from './harness.js';
import type { EvalMetrics } from './metrics.js';
import { ABLATION_ORDER, ROOT, listLogs, loadConfig, loadGraphFor, parseArgs, readLog } from './paths.js';

/**
 * Run every config over every log and write the ablation table.
 *
 *   pnpm ablation
 *
 * Writes docs/benchmarks.md, docs/benchmarks.csv, docs/benchmarks.json and
 * docs/ablation.svg, and prints the table.
 *
 * ★ EVERY CONFIG SEES EXACTLY THE SAME DRIVES ★
 * Same logs, same outage windows, same order. The only thing that varies is the
 * constraint set, which is the only way the table means what it says. The
 * engine is deterministic — asserted in nav-core's invariant tests — so a rerun
 * on another machine reproduces these numbers exactly.
 */

/** Three windows per log: an early outage, a late one, and a long one. */
const WINDOWS = [
  { startMs: 30_000, durationMs: 60_000 },
  { startMs: 60_000, durationMs: 45_000 },
  { startMs: 45_000, durationMs: 90_000 },
] as const;

interface Aggregate {
  config: string;
  description: string;
  runs: number;
  meanDriftPct: number;
  medianDriftPct: number;
  p90DriftPct: number;
  maxDriftPct: number;
  meanRmseM: number;
  meanAlongM: number;
  meanCrossM: number;
  meanCep95M: number;
  meanRecoveryS: number;
  meanUpdateHz: number;
  totalZupt: number;
  roadSnapPct: number;
  positionResets: number;
}

function stat(values: number[]): { mean: number; median: number; p90: number; max: number } {
  if (values.length === 0) return { mean: NaN, median: NaN, p90: NaN, max: NaN };
  const s = [...values].sort((a, b) => a - b);
  return {
    mean: s.reduce((a, b) => a + b, 0) / s.length,
    median: s[Math.floor(s.length / 2)]!,
    p90: s[Math.min(s.length - 1, Math.floor(s.length * 0.9))]!,
    max: s[s.length - 1]!,
  };
}

function mean(values: number[]): number {
  const finite = values.filter(Number.isFinite);
  return finite.length ? finite.reduce((a, b) => a + b, 0) / finite.length : NaN;
}

function f(v: number, d = 1): string {
  return Number.isFinite(v) ? v.toFixed(d) : 'n/a';
}

function svgChart(rows: Aggregate[]): string {
  const W = 900;
  const barH = 30;
  const gap = 10;
  const left = 210;
  const top = 56;
  const H = top + rows.length * (barH + gap) + 46;
  const maxVal = Math.max(...rows.map((r) => (Number.isFinite(r.meanDriftPct) ? r.meanDriftPct : 0)), 1);
  const scale = (W - left - 90) / maxVal;

  const bars = rows
    .map((r, i) => {
      const y = top + i * (barH + gap);
      const w = Math.max(1, (Number.isFinite(r.meanDriftPct) ? r.meanDriftPct : 0) * scale);
      // Green once inside the problem statement's <10% target, amber otherwise.
      const fill = r.meanDriftPct < 10 ? '#22c55e' : r.meanDriftPct < 30 ? '#eab308' : '#f97316';
      return `  <text x="${left - 12}" y="${y + barH * 0.68}" text-anchor="end" font-size="13" fill="#cbd5e1">${r.config}</text>
  <rect x="${left}" y="${y}" width="${w.toFixed(1)}" height="${barH}" rx="4" fill="${fill}" />
  <text x="${left + w + 10}" y="${y + barH * 0.68}" font-size="13" fill="#e2e8f0">${f(r.meanDriftPct, 1)}%</text>`;
    })
    .join('\n');

  const targetX = left + 10 * scale;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}" font-family="ui-sans-serif, system-ui, sans-serif">
  <rect width="${W}" height="${H}" fill="#0a0e14" />
  <text x="24" y="30" font-size="16" fill="#f1f5f9" font-weight="600">PathPulse — mean drift by constraint set</text>
  <text x="24" y="48" font-size="12" fill="#64748b">${rows[0]?.runs ?? 0} runs per configuration · lower is better · dashed line is the &lt;10% target</text>
${bars}
  <line x1="${targetX.toFixed(1)}" y1="${top - 8}" x2="${targetX.toFixed(1)}" y2="${H - 34}" stroke="#38bdf8" stroke-width="1.5" stroke-dasharray="5 4" />
  <text x="${(targetX + 6).toFixed(1)}" y="${H - 20}" font-size="11" fill="#38bdf8">10% target</text>
</svg>
`;
}

function markdown(rows: Aggregate[], logs: string[], graphNames: Set<string>): string {
  const simulated = logs.every((l) => l.startsWith('sim_'));
  return `# PathPulse benchmarks

**Generated by \`pnpm ablation\`. Do not edit by hand — rerun it.**

${rows[0]?.runs ?? 0} runs per configuration: ${logs.length} logs × ${WINDOWS.length} outage windows.
Ground truth is each log's own recorded GNSS, withheld from the estimator over
the outage window. Road graphs used: ${graphNames.size ? [...graphNames].join(', ') : 'none'}.

${
  simulated
    ? '> ⚠️ **Every log here is SIMULATED** (`sim_*.jsonl`), not driven. These numbers\n> measure the estimator against a physics model, not against a road. Real drive\n> logs belong alongside them as `drive_*.jsonl`; until then, do not present any\n> figure in this file as a road result.'
    : '> Includes real drive logs (`drive_*.jsonl`).'
}

## Drift

| Configuration | Mean % | Median % | p90 % | Max % | RMSE m | Along m | Cross m | CEP95 m |
|---|---|---|---|---|---|---|---|---|
${rows
  .map(
    (r) =>
      `| ${r.config} | **${f(r.meanDriftPct)}** | ${f(r.medianDriftPct)} | ${f(r.p90DriftPct)} | ${f(r.maxDriftPct)} | ${f(r.meanRmseM)} | ${f(r.meanAlongM)} | ${f(r.meanCrossM)} | ${f(r.meanCep95M)} |`,
  )
  .join('\n')}

![drift by configuration](./ablation.svg)

## Behaviour

| Configuration | Recovery s | Update Hz | ZUPT | Road snap % | Resets |
|---|---|---|---|---|---|
${rows
  .map(
    (r) =>
      `| ${r.config} | ${f(r.meanRecoveryS, 2)} | ${f(r.meanUpdateHz)} | ${r.totalZupt} | ${f(r.roadSnapPct)} | ${r.positionResets} |`,
  )
  .join('\n')}

## What each row is

${rows.map((r) => `- **${r.config}** — ${r.description}`).join('\n')}

## Reading this table

**Along-track and cross-track are separated on purpose.** A single error figure
says how wrong the estimate is; the split says *how* it is wrong, and the two
have different causes and different fixes. Cross-track error is what puts the
marker inside a building, and road geometry bounds it. Along-track error leaves
the marker on the right road at the wrong point along it, comes from speed
error, and road snapping deliberately does nothing about it.

**Drift % is final error over distance actually travelled**, taken from ground
truth rather than from the estimate's own idea of how far it went — otherwise a
configuration that under-estimates its speed would flatter itself twice.

**The p90 and max columns matter more than the mean.** A good mean hiding a bad
tail is exactly what someone finds by picking the one drive that went wrong.

## Reproducing

\`\`\`bash
pnpm eval:record     # regenerate the simulated logs (deterministic)
pnpm ablation        # rerun every configuration over every log
pnpm eval -- --log sim_city_4242.jsonl --config full   # one run, in detail
\`\`\`

The engine is deterministic — the same samples in produce byte-identical states
out, which nav-core's invariant tests assert — so these numbers reproduce
exactly on any machine.
`;
}

function csv(rows: Aggregate[]): string {
  const header = [
    'config',
    'runs',
    'mean_drift_pct',
    'median_drift_pct',
    'p90_drift_pct',
    'max_drift_pct',
    'mean_rmse_m',
    'mean_along_m',
    'mean_cross_m',
    'mean_cep95_m',
    'mean_recovery_s',
    'mean_update_hz',
    'zupt_triggers',
    'road_snap_pct',
    'position_resets',
  ].join(',');
  const body = rows
    .map((r) =>
      [
        r.config,
        r.runs,
        f(r.meanDriftPct, 3),
        f(r.medianDriftPct, 3),
        f(r.p90DriftPct, 3),
        f(r.maxDriftPct, 3),
        f(r.meanRmseM, 3),
        f(r.meanAlongM, 3),
        f(r.meanCrossM, 3),
        f(r.meanCep95M, 3),
        f(r.meanRecoveryS, 3),
        f(r.meanUpdateHz, 3),
        r.totalZupt,
        f(r.roadSnapPct, 3),
        r.positionResets,
      ].join(','),
    )
    .join('\n');
  return `${header}\n${body}\n`;
}

function main(): void {
  const args = parseArgs(process.argv);
  const logs = args.log ? [String(args.log)] : listLogs();
  if (logs.length === 0) {
    throw new Error('no logs in data/replay/ — run `pnpm eval:record` first');
  }

  const configNames = args.config ? [String(args.config)] : ABLATION_ORDER;
  const graphNames = new Set<string>();
  const rows: Aggregate[] = [];

  console.log(`\n  ${logs.length} logs × ${WINDOWS.length} windows × ${configNames.length} configs\n`);

  // Parse each log once and reuse it: parsing dominates the runtime otherwise.
  const parsed = new Map(logs.map((l) => [l, parseJsonl(readLog(l))]));

  for (const configName of configNames) {
    const config = loadConfig(configName);
    const results: EvalMetrics[] = [];

    for (const logName of logs) {
      const samples = parsed.get(logName)!;
      const firstFix = samples.find((s) => s.gnss)?.gnss;
      if (!firstFix) continue;

      const wantsGraph = config.engine.roadSnap !== false;
      const found = wantsGraph ? loadGraphFor(firstFix.lat, firstFix.lon) : null;
      if (found) graphNames.add(found.name);

      for (const w of WINDOWS) {
        const { metrics } = runEval(samples, {
          configName: config.name,
          logName,
          engineConfig: config.engine,
          outageStartMs: w.startMs,
          outageDurationMs: w.durationMs,
          roadGraph: found?.graph ?? null,
        });
        results.push(metrics);
      }
    }

    const drifts = results.map((r) => r.driftPercent).filter(Number.isFinite);
    const d = stat(drifts);
    rows.push({
      config: config.name,
      description: config.description ?? '',
      runs: results.length,
      meanDriftPct: d.mean,
      medianDriftPct: d.median,
      p90DriftPct: d.p90,
      maxDriftPct: d.max,
      meanRmseM: mean(results.map((r) => r.rmseM)),
      meanAlongM: mean(results.map((r) => Math.abs(r.alongTrackRmseM))),
      meanCrossM: mean(results.map((r) => Math.abs(r.crossTrackRmseM))),
      meanCep95M: mean(results.map((r) => r.cep95M)),
      meanRecoveryS: mean(
        results.map((r) => r.recoveryTimeS).filter((v): v is number => v !== null),
      ),
      meanUpdateHz: mean(results.map((r) => r.meanUpdateHz)),
      totalZupt: results.reduce((s, r) => s + r.zuptTriggers, 0),
      roadSnapPct: mean(results.map((r) => r.roadSnapAppliedPct)),
      positionResets: results.reduce((s, r) => s + r.positionResets, 0),
    });

    console.log(
      `  ${config.name.padEnd(18)} drift ${f(d.mean).padStart(6)}%   ` +
        `median ${f(d.median).padStart(6)}%   p90 ${f(d.p90).padStart(6)}%   max ${f(d.max).padStart(6)}%`,
    );
  }

  const docs = join(ROOT, 'docs');
  mkdirSync(docs, { recursive: true });
  writeFileSync(join(docs, 'benchmarks.md'), markdown(rows, logs, graphNames));
  writeFileSync(join(docs, 'benchmarks.csv'), csv(rows));
  writeFileSync(join(docs, 'ablation.svg'), svgChart(rows));
  writeFileSync(
    join(docs, 'benchmarks.json'),
    `${JSON.stringify({ generatedFrom: logs, windows: WINDOWS, rows }, null, 2)}\n`,
  );
  // The in-app Benchmarks screen reads this copy.
  const publicDocs = join(ROOT, 'apps', 'web', 'public', 'benchmarks');
  mkdirSync(publicDocs, { recursive: true });
  writeFileSync(
    join(publicDocs, 'benchmarks.json'),
    `${JSON.stringify({ generatedFrom: logs, windows: WINDOWS, rows }, null, 2)}\n`,
  );

  console.log('\n  wrote docs/benchmarks.md, .csv, .json and ablation.svg');
  console.log('  wrote apps/web/public/benchmarks/benchmarks.json for the in-app screen\n');

  const full = rows.find((r) => r.config === 'full');
  if (full && Number.isFinite(full.meanDriftPct)) {
    const verdict = full.meanDriftPct < 10 ? 'inside' : 'ABOVE';
    console.log(
      `  full: ${f(full.meanDriftPct)}% mean drift — ${verdict} the problem statement's <10% target`,
    );
    console.log(`  p90 is ${f(full.p90DriftPct)}% — quote the mean and someone will find the tail.\n`);
  }
}

try {
  main();
} catch (err) {
  console.error(`\n  ✖ ${(err as Error).message}\n`);
  process.exitCode = 1;
}
