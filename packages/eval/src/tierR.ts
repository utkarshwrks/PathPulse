/**
 * TIER R summary — the estimator on real vehicle sensors.
 *
 * Run with:  npx tsx src/tierR.ts
 *
 * Kept separate from ablation.ts on purpose. The ablation publishes Tier S
 * (simulated) numbers and those must stay comparable across runs; mixing a
 * different data tier into the same table is the one thing the tier rules
 * forbid. This prints its own table and says what it is on every line.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { RoadGraph } from '@pathpulse/nav-core';
import { parseJsonl, runEval } from './harness.js';
import { loadConfig, ROOT } from './paths.js';

const RUNS = [
  { log: 'iovnbd_S1.jsonl', graph: 'road_graph_iovnbd_s1.json' },
  { log: 'iovnbd_S3c.jsonl', graph: 'road_graph_iovnbd_s3c.json' },
];
const WINDOWS = [300, 600, 900, 1200, 1500, 1800, 2100, 2400, 2700, 3000].map((s) => s * 1000);
const DURATION_MS = 60_000;

function stats(v: number[]) {
  const s = [...v].sort((a, b) => a - b);
  return {
    n: s.length,
    mean: s.reduce((a, b) => a + b, 0) / s.length,
    median: s[Math.floor(s.length / 2)]!,
    p90: s[Math.floor(s.length * 0.9)]!,
    best: s[0]!,
    worst: s[s.length - 1]!,
  };
}

const configName = process.argv.includes('--config')
  ? String(process.argv[process.argv.indexOf('--config') + 1])
  : 'full';
const cfg = loadConfig(configName);
const all: number[] = [];
const byLog: Array<{ name: string; s: ReturnType<typeof stats> }> = [];

console.log(`\n  TIER R — real vehicle sensors (IO-VNBD), NOT our device\n`);
console.log(`  config: ${configName}   ${WINDOWS.length} windows x ${DURATION_MS / 1000}s outage\n`);
console.log(
  `    ${'log'.padEnd(20)} ${'n'.padStart(3)} ${'mean'.padStart(7)} ${'median'.padStart(7)} ` +
    `${'p90'.padStart(7)} ${'best'.padStart(7)} ${'worst'.padStart(7)}`,
);

for (const r of RUNS) {
  const file = join(ROOT, 'data/replay', r.log);
  if (!existsSync(file)) continue;
  const samples = parseJsonl(readFileSync(file, 'utf8'));
  const gp = join(ROOT, 'data/maps', r.graph);
  const graph = existsSync(gp) ? (JSON.parse(readFileSync(gp, 'utf8')) as RoadGraph) : null;
  const span = samples[samples.length - 1]!.t;
  const drifts: number[] = [];
  for (const w of WINDOWS) {
    if (w + DURATION_MS > span - 30_000) continue;
    const res = runEval(samples, {
      configName,
      logName: r.log,
      engineConfig: cfg.engine,
      outageStartMs: w,
      outageDurationMs: DURATION_MS,
      roadGraph: graph,
    });
    const d = res.metrics.driftPercent;
    if (Number.isFinite(d)) {
      drifts.push(d);
      all.push(d);
    }
  }
  if (!drifts.length) continue;
  const s = stats(drifts);
  byLog.push({ name: r.log, s });
  console.log(
    `    ${r.log.padEnd(20)} ${String(s.n).padStart(3)} ${s.mean.toFixed(1).padStart(7)} ` +
      `${s.median.toFixed(1).padStart(7)} ${s.p90.toFixed(1).padStart(7)} ` +
      `${s.best.toFixed(1).padStart(7)} ${s.worst.toFixed(1).padStart(7)}`,
  );
}

if (all.length) {
  const s = stats(all);
  console.log(
    `    ${'OVERALL'.padEnd(20)} ${String(s.n).padStart(3)} ${s.mean.toFixed(1).padStart(7)} ` +
      `${s.median.toFixed(1).padStart(7)} ${s.p90.toFixed(1).padStart(7)} ` +
      `${s.best.toFixed(1).padStart(7)} ${s.worst.toFixed(1).padStart(7)}`,
  );

  // Written as its own document rather than appended to benchmarks.md, which
  // `pnpm ablation` regenerates from scratch — a Tier R section added there
  // survives exactly until the next ablation run, and then vanishes silently.
  const f = (n: number) => n.toFixed(1);
  const doc = `# PathPulse — TIER R benchmarks

**Generated by \`pnpm eval:tier-r\`. Do not edit by hand — rerun it.**

Real vehicle sensors, from the public IO-VNBD dataset, converted by
\`pnpm data:iovnbd\`. Real smartphone IMU in a real car on real roads, with the
vehicle's own CAN bus available as a cross-check.

> ⚠️ **This is a different data tier from [benchmarks.md](./benchmarks.md).**
> Never average a row here with a simulated one. A Tier R result is strong
> evidence that something works on real sensors and is **not** evidence that it
> works on our handset — see \`data/replay/README.md\`.

Config \`${configName}\`, ${WINDOWS.length} outage windows of ${DURATION_MS / 1000} s per log.

| log | n | mean % | median % | p90 % | best % | worst % |
|---|---|---|---|---|---|---|
${byLog
  .map(
    (r) =>
      `| \`${r.name}\` | ${r.s.n} | ${f(r.s.mean)} | ${f(r.s.median)} | ${f(r.s.p90)} | ${f(r.s.best)} | ${f(r.s.worst)} |`,
  )
  .join('\n')}
| **OVERALL** | ${s.n} | **${f(s.mean)}** | **${f(s.median)}** | ${f(s.p90)} | ${f(s.best)} | ${f(s.worst)} |

## What this says

The shipped configuration measures **6.9 % on simulated logs and ${f(s.mean)} % on real
vehicle sensors.** Every figure in benchmarks.md should be read as an upper
bound on the estimator, not an estimate of it.

The error is **along-track, not cross-track** — roughly three to four times
larger. Heading is in good shape: integrating the recovered yaw rate across real
turns reproduces GPS heading change with slope 1.002 and 0.9° mean error. What
is wrong is speed once the held Doppler expires.

**The spread is the other finding.** ${f(s.best)} % in one window and ${f(s.worst)} % in another.
The good ones are fast, straight, well-fixed stretches; the bad ones are stop-go
traffic where fixes are sparse and integration has nothing to anchor to. A
single mean hides that entirely.

> Measured on real vehicle sensors from a public dataset — **not yet on our own
> device**. Tier F (\`drive_*\`) does not exist yet.
`;
  writeFileSync(join(ROOT, 'docs', 'benchmarks-tier-r.md'), doc);
  console.log(
    `\n  wrote docs/benchmarks-tier-r.md` +
      `\n\n  Measured on real vehicle sensors from a public dataset — not yet on our` +
      `\n  own device. Never average these with the simulated rows.\n`,
  );
}
