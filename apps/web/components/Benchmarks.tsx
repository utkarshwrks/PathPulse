'use client';

import { useEffect, useState } from 'react';

export interface BenchmarkRow {
  config: string;
  description: string;
  runs: number;
  meanDriftPct: number;
  medianDriftPct: number;
  p90DriftPct: number;
  maxDriftPct: number;
  meanRmseM: number;
  meanAlongM: number;
  meanCrossM: number;
  meanCep95M: number;
  meanRecoveryS: number;
  meanUpdateHz: number;
  totalZupt: number;
  roadSnapPct: number;
  positionResets: number;
}

export interface BenchmarkData {
  generatedFrom: string[];
  windows: Array<{ startMs: number; durationMs: number }>;
  rows: BenchmarkRow[];
}

interface BenchmarksProps {
  onClose: () => void;
  /** Injected by tests; production fetches from the app's own assets. */
  data?: BenchmarkData | null;
}

/**
 * Phase 7D — the ablation table, in the app.
 *
 * ★ THE STRONGEST SLIDE, AND IT LIVES IN THE DEMO ★
 * The table is the thing that separates this from a project that merely claims
 * a number: every row is measured, against ground truth the estimator never
 * saw, and each row differs from the one above it by exactly one constraint.
 * Keeping it in the app means never switching to a laptop mid-demo.
 *
 * The data is generated by `pnpm ablation` into public/benchmarks — never
 * computed here. A screen that recomputed its own benchmark would be marking
 * its own homework, and would disagree with the committed table the moment
 * anything drifted.
 */
export default function Benchmarks({ onClose, data: injected }: BenchmarksProps) {
  const [data, setData] = useState<BenchmarkData | null>(injected ?? null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    if (injected !== undefined) return;
    let cancelled = false;
    fetch('benchmarks/benchmarks.json')
      .then((r) => (r.ok ? (r.json() as Promise<BenchmarkData>) : Promise.reject(new Error('missing'))))
      .then((d) => !cancelled && setData(d))
      .catch(() => !cancelled && setError('no benchmarks bundled — run `pnpm ablation`'));
    return () => {
      cancelled = true;
    };
  }, [injected]);

  const simulated = data?.generatedFrom.every((l) => l.startsWith('sim_')) ?? false;
  const best = data?.rows.find((r) => r.config === 'full');

  return (
    <div className="absolute inset-0 z-30 overflow-y-auto bg-[#0a0e14]/97 backdrop-blur">
      <div className="mx-auto max-w-3xl px-4 py-5">
        <div className="mb-4 flex items-center justify-between">
          <div>
            <h2 className="text-base font-semibold text-neutral-100">Benchmarks</h2>
            <p className="text-[11px] text-neutral-500">
              Measured, not claimed — each row adds one constraint
            </p>
          </div>
          <button
            type="button"
            onClick={onClose}
            className="rounded-lg border border-white/15 px-3 py-1.5 text-xs text-neutral-200 transition hover:bg-white/10"
          >
            Close
          </button>
        </div>

        {error ? <p className="text-[12px] text-amber-400">{error}</p> : null}
        {!data && !error ? <p className="text-[12px] text-neutral-500">loading…</p> : null}

        {data ? (
          <>
            {best ? (
              <div className="mb-4 rounded-xl border border-white/10 bg-white/5 px-4 py-3">
                <div className="flex items-baseline gap-2">
                  <span className="tabular font-mono text-3xl font-semibold text-neutral-50">
                    {best.meanDriftPct.toFixed(1)}%
                  </span>
                  <span className="text-[11px] text-neutral-400">mean drift, full configuration</span>
                </div>
                <p className="mt-1 text-[11px] leading-snug text-neutral-400">
                  p90 {best.p90DriftPct.toFixed(1)}% · worst {best.maxDriftPct.toFixed(1)}% ·{' '}
                  {best.runs} runs. The tail matters more than the mean — it is what
                  someone finds by picking the one drive that went wrong.
                </p>
              </div>
            ) : null}

            {simulated ? (
              <p className="mb-4 rounded-lg border border-amber-500/30 bg-amber-500/10 px-3 py-2 text-[11px] leading-snug text-amber-200">
                Every log here is <strong>simulated</strong>, not driven. These numbers measure
                the estimator against a physics model, not against a road. Do not present any
                figure on this screen as a road result.
              </p>
            ) : null}

            <div className="overflow-x-auto">
              <table className="tabular w-full min-w-[34rem] border-collapse font-mono text-[11px]">
                <thead>
                  <tr className="border-b border-white/15 text-left text-neutral-500">
                    <th className="py-1.5 pr-3 font-medium">config</th>
                    <th className="py-1.5 pr-3 text-right font-medium">drift %</th>
                    <th className="py-1.5 pr-3 text-right font-medium">p90</th>
                    <th className="py-1.5 pr-3 text-right font-medium">RMSE</th>
                    <th className="py-1.5 pr-3 text-right font-medium">along</th>
                    <th className="py-1.5 text-right font-medium">cross</th>
                  </tr>
                </thead>
                <tbody>
                  {data.rows.map((r) => {
                    const negative = r.config === 'full_forwardbias';
                    return (
                      <tr
                        key={r.config}
                        className={`border-b border-white/5 ${
                          r.config === 'full' ? 'bg-emerald-500/10' : ''
                        }`}
                      >
                        <td className={`py-1.5 pr-3 ${negative ? 'text-neutral-500 line-through' : 'text-neutral-200'}`}>
                          {r.config}
                        </td>
                        <td
                          className={`py-1.5 pr-3 text-right ${
                            r.meanDriftPct < 10 ? 'text-emerald-300' : 'text-neutral-200'
                          }`}
                        >
                          {r.meanDriftPct.toFixed(1)}
                        </td>
                        <td className="py-1.5 pr-3 text-right text-neutral-400">
                          {r.p90DriftPct.toFixed(1)}
                        </td>
                        <td className="py-1.5 pr-3 text-right text-neutral-400">
                          {r.meanRmseM.toFixed(0)}
                        </td>
                        <td className="py-1.5 pr-3 text-right text-neutral-400">
                          {r.meanAlongM.toFixed(0)}
                        </td>
                        <td className="py-1.5 text-right text-neutral-400">
                          {r.meanCrossM.toFixed(0)}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>

            <p className="mt-3 text-[10.5px] leading-relaxed text-neutral-500">
              <strong className="text-neutral-400">Along and cross are separated on purpose.</strong>{' '}
              A single error figure says how wrong we are; the split says how. Cross-track error
              puts the marker inside a building and road geometry bounds it. Along-track leaves
              it on the right road at the wrong point, comes from speed error, and road snapping
              deliberately does nothing about it.
            </p>
            <p className="mt-2 text-[10.5px] leading-relaxed text-neutral-500">
              <strong className="text-neutral-400">The struck-through row is a negative result.</strong>{' '}
              The forward-bias estimator was a clear win until the acceleration high-pass
              replaced it; stacking both is measurably worse, so it ships disabled and is
              reported rather than deleted.
            </p>
            <p className="mt-2 text-[10.5px] text-neutral-600">
              {data.rows[0]?.runs ?? 0} runs per configuration ·{' '}
              {data.generatedFrom.length} logs × {data.windows.length} outage windows · ground
              truth is each log&apos;s own GNSS, withheld from the estimator
            </p>
          </>
        ) : null}
      </div>
    </div>
  );
}
